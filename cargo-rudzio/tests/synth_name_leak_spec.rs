//! Defensive spec: internal crate-wrapper / synth names introduced
//! by per-binary scoping MUST NOT leak into user-visible test output
//! (Bug #10 sub-clause).
//!
//! # Context
//!
//! Bug #10's per-binary scoping rewrites helper file mounts at the
//! aggregator's crate root using a synth prefix
//! (`__rudzio__<binary_id>__<helper>`) so two `[[test]]` binaries
//! declaring `mod common;` against DIFFERENT files don't collide.
//! That synth prefix is implementation detail — it must never reach:
//!
//! 1. **Static surface.** Emitted aggregator source must not embed
//!    the synth string as a literal that would land in a printed
//!    field (e.g. the `name` arg of `Source::new(file, line,
//!    module_path, name)`).
//! 2. **Behavioral surface.** A panicking / failing test's stdout +
//!    stderr — what a human reads when debugging — must not contain
//!    the synth substring.
//! 3. **Normalization shield.** `rudzio::normalize_module_path` —
//!    the runtime's last line of defense against autogenerated
//!    segments — must strip any `__rudzio__*` segment even if the
//!    codegen ever regresses and emits one through `module_path!()`.
//!
//! All three layers are exercised here so a regression at any layer
//! is caught. Pre-Bug-#10-fix the codebase emits no synth names so
//! these tests pass trivially; their value is post-fix forward-
//! looking. The static + behavioral layers operate on a fixture
//! shaped to force per-binary scoping (two binaries × same helper
//! name × different files). The normalization layer is a pure unit
//! test against the public `normalize_module_path` function.

use std::env;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

use cargo_rudzio::generate::{plan_from_manifest, write_runner};
use cargo_rudzio_test_helpers::{IsolatedCargoSuite, IsolatedCargoTest};
use rudzio::runtime::tokio::Multithread as TokioMultithread;
use rudzio::{normalize_module_path, qualified_test_name};
use tempfile::TempDir;

/// Common prefix every internal aggregator-wrapper name carries.
///
/// Two families currently exist:
///
/// - `__rudzio__<binary_id>__<helper>` — Bug #10 per-binary helper
///   scoping. Double-underscore separators throughout.
/// - `__rudzio_member_tests` — the wrapper module main.rs uses to
///   nest member tests under a name that doesn't collide with
///   member-`src::tests` modules. Single-underscore separators.
///
/// Both must NOT surface in user-visible test names, panic traces,
/// or junit-style report fields. Matching on the shared `__rudzio`
/// prefix catches every member of the family — new wrapper names
/// added in the future get caught for free as long as they keep the
/// `__rudzio` prefix convention.
const SYNTH_MARKER: &str = "__rudzio";

/// Workspace root of the in-tree rudzio package.
fn rudzio_source_root() -> PathBuf {
    rudzio::manifest_dir!().join("..")
}

/// Single-binary fixture with a `common` helper. Exercises the
/// Bug #10 per-binary scoping (the binary's helper still goes
/// through `__rudzio__<binary_id>__common` synth-name generation
/// even with one binary), without triggering the collision
/// detector (which fires when TWO binaries declare the same
/// helper name against DIFFERENT files).
fn write_fixture(root: &Path, rudzio_root: &Path) -> io::Result<()> {
    fs::write(
        root.join("Cargo.toml"),
        format!(
            "[workspace]\n\
             members = [\"consumer\"]\n\
             resolver = \"3\"\n\
             \n\
             [workspace.dependencies]\n\
             rudzio = {{ path = \"{rudzio}\", default-features = false, features = [\"common\", \"runtime-tokio-multi-thread\"] }}\n",
            rudzio = rudzio_root.display(),
        ),
    )?;
    let consumer = root.join("consumer");
    fs::create_dir_all(consumer.join("src"))?;
    fs::write(
        consumer.join("Cargo.toml"),
        "[package]\n\
         name = \"consumer\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         autotests = false\n\
         \n\
         [lib]\n\
         name = \"consumer\"\n\
         path = \"src/lib.rs\"\n\
         \n\
         [[test]]\n\
         name = \"integration\"\n\
         path = \"tests/integration/mod.rs\"\n\
         harness = false\n\
         \n\
         [dev-dependencies]\n\
         rudzio = { workspace = true }\n\
         anyhow = \"=1.0.102\"\n",
    )?;
    fs::write(
        consumer.join("src").join("lib.rs"),
        "// rudzio_test marker\n",
    )?;
    write_test_binary(&consumer, "integration", "INTEGRATION_TOKEN")?;
    Ok(())
}

/// One `[[test]]` binary at `consumer/tests/<name>/` with a private
/// `common.rs` helper whose `token_name` constant disambiguates it
/// from the other binary's `common.rs`.
fn write_test_binary(consumer: &Path, name: &str, token_name: &str) -> io::Result<()> {
    let dir = consumer.join("tests").join(name);
    fs::create_dir_all(&dir)?;
    fs::write(
        dir.join("mod.rs"),
        "// rudzio_test marker\n\
         #![allow(clippy::tests_outside_test_module)]\n\
         \n\
         mod common;\n\
         mod foo;\n\
         \n\
         #[rudzio::main]\n\
         fn main() {}\n",
    )?;
    fs::write(
        dir.join("common.rs"),
        format!("pub(crate) const {token_name}: () = ();\n"),
    )?;
    fs::write(
        dir.join("foo.rs"),
        format!(
            "use rudzio::common::context::{{Suite, Test}};\n\
             use rudzio::runtime::tokio::Multithread as TokioMultithread;\n\
             \n\
             #[rudzio::suite([(runtime = TokioMultithread::new, suite = Suite, test = Test)])]\n\
             mod tests {{\n\
             \x20\x20\x20\x20use crate::common::{token_name};\n\
             \n\
             \x20\x20\x20\x20#[rudzio::test]\n\
             \x20\x20\x20\x20fn deliberately_panics_for_leak_check() {{\n\
             \x20\x20\x20\x20\x20\x20\x20\x20let _: () = {token_name};\n\
             \x20\x20\x20\x20\x20\x20\x20\x20panic!(\"intentional panic to surface the test name in stderr\");\n\
             \x20\x20\x20\x20}}\n\
             }}\n",
        ),
    )?;
    Ok(())
}

/// `CARGO_NET_OFFLINE=true` guard. Same RAII pattern as the other
/// specs in this directory.
fn with_cargo_offline<F, T>(body: F) -> T
where
    F: FnOnce() -> T,
{
    /// RAII restore.
    struct Restore {
        /// Previous value (`None` = was unset).
        prev: Option<String>,
    }
    impl Drop for Restore {
        fn drop(&mut self) {
            if let Some(prev) = self.prev.take() {
                #[expect(
                    unsafe_code,
                    reason = "std::env::set_var marked unsafe; guard owns the var"
                )]
                // SAFETY: see other specs.
                unsafe {
                    env::set_var("CARGO_NET_OFFLINE", prev);
                }
            } else {
                #[expect(
                    unsafe_code,
                    reason = "std::env::remove_var marked unsafe; guard owns the var"
                )]
                // SAFETY: see other specs.
                unsafe {
                    env::remove_var("CARGO_NET_OFFLINE");
                }
            }
        }
    }
    let prev = env::var("CARGO_NET_OFFLINE").ok();
    let _guard = Restore { prev };
    #[expect(
        unsafe_code,
        reason = "std::env::set_var marked unsafe; guard owns the var"
    )]
    // SAFETY: see Restore::drop.
    unsafe {
        env::set_var("CARGO_NET_OFFLINE", "true");
    }
    body()
}

/// Recursively concatenate every `.rs` + `.toml` under `out_dir`.
fn read_emitted_sources(out_dir: &Path) -> io::Result<String> {
    let mut buf = String::new();
    let mut stack: Vec<PathBuf> = vec![out_dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for raw_entry in fs::read_dir(&dir)? {
            let entry = raw_entry?;
            let kind = entry.file_type()?;
            let path = entry.path();
            if kind.is_dir() {
                stack.push(path);
            } else if !kind.is_dir()
                && path
                    .extension()
                    .is_some_and(|extension| extension == "rs" || extension == "toml")
                && let Ok(text) = fs::read_to_string(&path)
            {
                buf.push_str(&text);
                buf.push('\n');
            } else {
                // Other file type or non-.rs/.toml — ignored.
            }
        }
    }
    Ok(buf)
}

/// `true` when `line` looks like a Rust panic backtrace frame:
/// indented + numeric index + colon + hex address + ` - `. Rust
/// emits these from its built-in panic hook; the leak detector
/// excludes them because the synth-named symbols they reference
/// are the actual Rust mangled names, which rudzio cannot rewrite
/// without breaking debugger workflows.
fn is_rust_backtrace_line(line: &str) -> bool {
    let trimmed = line.trim_start();
    let mut chars = trimmed.chars();
    let first_digit = chars
        .next()
        .is_some_and(|character| character.is_ascii_digit());
    if !first_digit {
        return false;
    }
    // Look for ` 0x` after the leading index — the hex address is
    // the unambiguous backtrace-frame signal.
    line.contains(" 0x")
}

/// `true` when `line` looks like cargo's pre-test build output
/// (`Compiling …`, `Finished …`, `Updating …`, `Locking …`,
/// `Running …`, `error[…]: …`). These are cargo's own emissions,
/// not rudzio's runner output. The leak detector excludes them
/// because rudzio doesn't control cargo's formatting of internal
/// crate names; the synth-name leak the user reported only
/// matters in rudzio's own output (status lines, failure
/// summaries, `--list`).
fn is_cargo_build_line(line: &str) -> bool {
    let trimmed = line.trim_start();
    trimmed.starts_with("Compiling ")
        || trimmed.starts_with("Finished ")
        || trimmed.starts_with("Updating ")
        || trimmed.starts_with("Locking ")
        || trimmed.starts_with("Running ")
        || trimmed.starts_with("error[")
        || trimmed.starts_with("warning:")
        || trimmed.starts_with("note:")
        || trimmed.starts_with("help:")
        || trimmed.starts_with('=')
        // Compiler diagnostics frequently use a leading pipe `|`
        // for source-line decoration; same scope as warnings.
        || trimmed.starts_with('|')
        || trimmed.starts_with("--> ")
}

/// Extract every `"…"` string literal from `text`. Tolerates escaped
/// quotes via a tiny state machine — good enough for spotting synth
/// names in TOML + Rust without dragging in a parser.
fn collect_string_literals(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut chars = text.chars();
    while let Some(character) = chars.next() {
        if character != '"' {
            continue;
        }
        let mut literal = String::new();
        let mut escaped = false;
        for inner in chars.by_ref() {
            if escaped {
                literal.push(inner);
                escaped = false;
            } else if inner == '\\' {
                literal.push(inner);
                escaped = true;
            } else if inner == '"' {
                break;
            } else {
                literal.push(inner);
            }
        }
        out.push(literal);
    }
    out
}

#[rudzio::suite([
    (runtime = TokioMultithread::new, suite = IsolatedCargoSuite, test = IsolatedCargoTest),
])]
mod tests {
    use super::{
        Command, IsolatedCargoTest, Path, SYNTH_MARKER, TempDir, collect_string_literals, env, fs,
        is_cargo_build_line, is_rust_backtrace_line, normalize_module_path, plan_from_manifest,
        qualified_test_name, read_emitted_sources, rudzio_source_root, with_cargo_offline,
        write_fixture, write_runner,
    };

    /// Layer 1 — static: synth names must NEVER appear in string
    /// literals in the emitted aggregator source. `mod __rudzio__…;`
    /// declarations + `crate::__rudzio__…` use paths in proxy
    /// files are allowed (they're identifier-level wiring, not
    /// strings), but a synth name inside a `"…"` literal would
    /// surface verbatim at runtime.
    #[rudzio::test]
    fn no_synth_marker_in_emitted_string_literals(ctx: &IsolatedCargoTest) -> anyhow::Result<()> {
        let temp = TempDir::new_in(ctx.suite_tempdir())?;
        let rudzio_root = rudzio_source_root();
        write_fixture(temp.path(), &rudzio_root)?;
        let manifest = temp.path().join("Cargo.toml");
        // `plan_from_manifest` runs `cargo metadata --no-deps`
        // in-process; `--no-deps` skips registry reads, so the
        // inherited (system) `CARGO_HOME` is fine here. The
        // `with_cargo_offline` guard is belt-and-suspenders for
        // environments where cargo might still try to refresh the
        // index.
        let plan = with_cargo_offline(|| plan_from_manifest(&manifest))?;
        let out_dir = plan.default_output_dir();
        write_runner(&plan, &out_dir)?;
        let emitted = read_emitted_sources(&out_dir)?;
        let mut offenders: Vec<String> = Vec::new();
        for literal in collect_string_literals(&emitted) {
            if literal.contains(SYNTH_MARKER) {
                offenders.push(literal);
            }
        }
        anyhow::ensure!(
            offenders.is_empty(),
            "synth marker `{SYNTH_MARKER}` leaked into emitted string literals; \
             these strings reach user output verbatim:\n  {}",
            offenders.join("\n  "),
        );
        Ok(())
    }

    /// Layer 2 — behavioral: run the aggregator with a deliberately-
    /// panicking test, capture stdout + stderr, and assert the synth
    /// marker doesn't appear in rudzio's own runner output. Catches
    /// leaks via `module_path!()` expansion inside helper-rooted
    /// code, runner status lines, failure summaries, and `--list`
    /// output.
    ///
    /// **Exclusions.** Two classes of output are filtered before
    /// the check:
    ///
    /// 1. **Rust panic backtraces** (lines containing a hex
    ///    pointer like ` 0x` followed by ` - `). Backtraces print
    ///    actual Rust symbols verbatim, which is the correct
    ///    debugger behavior; rudzio cannot rewrite them.
    /// 2. **Cargo build output** (lines starting with `Compiling`,
    ///    `Finished`, `Updating`, `Locking`, `Running`, or `error[`).
    ///    These are cargo's own pre-test output, not rudzio's.
    ///
    /// What remains is rudzio's runner output proper — the lines a
    /// human sees AFTER the build phase. Synth names in that scope
    /// would be the leak the user reported (`__rudzio_member_tests::
    /// cargo_rudzio::...` lines from rudzio's `[OK]`/`[FAIL]`
    /// status emit).
    #[rudzio::test]
    fn no_synth_marker_in_aggregator_stdout_or_stderr(
        ctx: &IsolatedCargoTest,
    ) -> anyhow::Result<()> {
        let temp = TempDir::new_in(ctx.suite_tempdir())?;
        let rudzio_root = rudzio_source_root();
        write_fixture(temp.path(), &rudzio_root)?;
        let manifest = temp.path().join("Cargo.toml");
        let cargo_rudzio = env!("CARGO_BIN_EXE_cargo-rudzio");
        // Per-test cargo state (hardlinked from suite pre-warm) +
        // offline mode = no flock contention, no host-target
        // accumulation. Aggregator subtree lives in
        // `ctx.cargo_target_dir()` and vanishes at test drop.
        let output = Command::new(cargo_rudzio)
            .arg("test")
            .arg("--manifest-path")
            .arg(&manifest)
            .env(
                "CARGO",
                env::var_os("CARGO").unwrap_or_else(|| "cargo".into()),
            )
            .env("CARGO_HOME", ctx.cargo_home())
            .env("CARGO_TARGET_DIR", ctx.cargo_target_dir())
            .env("CARGO_NET_OFFLINE", "true")
            .output()?;
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        let combined = format!("{stdout}\n{stderr}");
        // Filter backtrace and cargo-build lines before scanning.
        let runner_lines: Vec<&str> = combined
            .lines()
            .filter(|line| !is_rust_backtrace_line(line))
            .filter(|line| !is_cargo_build_line(line))
            .collect();
        let leaking: Vec<&&str> = runner_lines
            .iter()
            .filter(|line| line.contains(SYNTH_MARKER))
            .collect();
        anyhow::ensure!(
            leaking.is_empty(),
            "synth marker `{SYNTH_MARKER}` leaked into rudzio's runner output; \
             a human reading the test report would see the internal name. \
             Leaking lines:\n{}",
            leaking
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join("\n"),
        );
        Ok(())
    }

    /// Layer 3 — normalization shield. The runtime's last line of
    /// defense against autogenerated module segments must drop EVERY
    /// `__rudzio*` segment, so a codegen regression doesn't surface
    /// verbatim. Pure unit test against the public
    /// `normalize_module_path` function — no fixture, no I/O.
    ///
    /// Pre-fix this assertion FAILS: `normalize_module_path` only
    /// strips the leading crate name, the literal `tests`
    /// aggregator-wrapper segment, and the `main` shim segment; it
    /// does NOT touch the actual wrapper modules the aggregator
    /// emits (`__rudzio_member_tests`, `__rudzio__<id>__<helper>`).
    ///
    /// Three live shapes are covered:
    ///
    /// 1. `__rudzio_member_tests` — the wrapper main.rs uses to nest
    ///    member tests under a name that doesn't collide with
    ///    `member-src::tests`. Currently leaks verbatim into test
    ///    output (e.g. `[OK] __rudzio_member_tests::cargo_rudzio::
    ///    crate_path_under_aggregator_spec::...`).
    /// 2. `__rudzio__<id>__<helper>` — Bug #10's per-binary helper
    ///    scoping. Hypothetical (only present after Bug #10 fix
    ///    lands), but assertion guards against codegen regression.
    /// 3. Solo synth segment — when stripping leaves the synth
    ///    segment as the ONLY survivor, the result must be empty
    ///    rather than the wrapper alone leaking through.
    #[rudzio::test]
    fn normalize_module_path_strips_synth_segments() -> anyhow::Result<()> {
        // Shape 1: the wrapper marker currently leaking in live runs.
        // `aggregator::__rudzio_member_tests::cargo_rudzio::foo_spec::
        // bar` → user-visible form `cargo_rudzio::foo_spec::bar`.
        let wrapper = "aggregator::__rudzio_member_tests::cargo_rudzio::foo_spec::bar";
        let normalized_wrapper = normalize_module_path(wrapper);
        anyhow::ensure!(
            !normalized_wrapper.contains(SYNTH_MARKER),
            "normalize_module_path did NOT strip `__rudzio_member_tests` from {wrapper:?}; \
             got {normalized_wrapper:?} (still contains `{SYNTH_MARKER}`)",
        );

        // Shape 2: per-binary synth helper segment (Bug #10).
        let helper = "aggregator::__rudzio__consumer__integration__common::tests";
        let normalized_helper = normalize_module_path(helper);
        anyhow::ensure!(
            !normalized_helper.contains(SYNTH_MARKER),
            "normalize_module_path did NOT strip Bug #10 synth helper segment from {helper:?}; \
             got {normalized_helper:?} (still contains `{SYNTH_MARKER}`)",
        );

        // Shape 3: solo synth segment must not surface alone.
        let solo = "aggregator::__rudzio__consumer__integration__common";
        let normalized_solo = normalize_module_path(solo);
        anyhow::ensure!(
            !normalized_solo.contains(SYNTH_MARKER),
            "normalize_module_path leaked a solo synth segment from {solo:?}; \
             got {normalized_solo:?}",
        );
        Ok(())
    }

    /// Layer 4 — composition shield: `qualified_test_name` is the
    /// function that actually renders the user-visible
    /// `<module>::<name>` label in status lines, `--list` output,
    /// and failure summaries. Even if `normalize_module_path` does
    /// its job, a future caller that builds display names by
    /// concatenating `token.module_path` + `token.name` directly
    /// (skipping `normalize_module_path`) would leak. Guard the
    /// composed function so any such regression fails here.
    #[rudzio::test]
    fn qualified_test_name_strips_synth_segments() -> anyhow::Result<()> {
        // Most realistic shape: aggregator-rendered module path
        // containing the wrapper marker, joined with a test name.
        let module_path = "rudzio_auto_runner::__rudzio_member_tests::cargo_rudzio::foo_spec";
        let test_name = "bar";
        let display = qualified_test_name(module_path, test_name);
        anyhow::ensure!(
            !display.contains(SYNTH_MARKER),
            "qualified_test_name leaked synth marker; module_path={module_path:?}, \
             name={test_name:?}, display={display:?}",
        );
        anyhow::ensure!(
            display.ends_with("bar"),
            "qualified_test_name must preserve the trailing test name; got {display:?}",
        );
        Ok(())
    }

    /// Layer 5 — degenerate input: when every segment is
    /// autogenerated (crate name + synth wrapper only), the
    /// normalized path must be empty. `qualified_test_name`
    /// composes that with the test name and returns just the name
    /// — no double `::` artifacts, no synth residue.
    #[rudzio::test]
    fn qualified_test_name_handles_path_that_normalizes_to_empty() -> anyhow::Result<()> {
        let module_path = "rudzio_auto_runner::__rudzio_member_tests";
        let test_name = "bare";
        let normalized = normalize_module_path(module_path);
        anyhow::ensure!(
            normalized.is_empty(),
            "all-autogenerated path must normalize to empty; got {normalized:?}",
        );
        let display = qualified_test_name(module_path, test_name);
        anyhow::ensure!(
            display == "bare",
            "qualified_test_name on empty-normalized path must equal the test name; \
             got {display:?}",
        );
        anyhow::ensure!(
            !display.contains("::"),
            "qualified_test_name must not emit dangling `::` when module portion is empty; \
             got {display:?}",
        );
        Ok(())
    }

    /// Layer 6 — idempotence guard: `normalize_module_path` MUST
    /// NOT over-strip. A clean, user-authored path
    /// (`my_crate::tests::feature::it_works`) must round-trip
    /// through normalize correctly. Pre-strip: drop the leading
    /// crate name + the literal `tests` aggregator wrapper; the
    /// `feature` segment is user-authored and must survive.
    #[rudzio::test]
    fn normalize_module_path_preserves_user_authored_segments() -> anyhow::Result<()> {
        let module_path = "my_crate::tests::feature::it_works";
        let normalized = normalize_module_path(module_path);
        anyhow::ensure!(
            normalized.contains("feature"),
            "user-authored `feature` segment must survive normalize; got {normalized:?}",
        );
        anyhow::ensure!(
            normalized.contains("it_works"),
            "user-authored `it_works` segment must survive normalize; got {normalized:?}",
        );
        anyhow::ensure!(
            !normalized.starts_with("my_crate"),
            "leading crate name must be stripped; got {normalized:?}",
        );
        Ok(())
    }

    /// Sanity check: the fixture path-pins rudzio against an in-tree
    /// source so the leak tests don't depend on network reachability.
    /// Catches setup regressions early instead of letting them
    /// manifest as opaque cargo errors from layer 2.
    #[rudzio::test]
    fn fixture_writes_consumer_with_one_binary_and_helper(
        ctx: &IsolatedCargoTest,
    ) -> anyhow::Result<()> {
        let temp = TempDir::new_in(ctx.suite_tempdir())?;
        let rudzio_root = rudzio_source_root();
        write_fixture(temp.path(), &rudzio_root)?;
        let workspace_toml = fs::read_to_string(temp.path().join("Cargo.toml"))?;
        let consumer_toml = fs::read_to_string(temp.path().join("consumer").join("Cargo.toml"))?;
        anyhow::ensure!(
            workspace_toml.contains("rudzio = { path ="),
            "fixture workspace must path-pin rudzio for offline runs",
        );
        anyhow::ensure!(
            consumer_toml.matches("[[test]]").count() == 1,
            "fixture must declare exactly one `[[test]]` binary (multi-binary fixtures trigger Bug #10 collision detection)",
        );
        // No-op `Path` use so the top-of-file import isn't flagged
        // as unused when the inner module is the only consumer.
        let _: &Path = Path::new(env!("CARGO_BIN_EXE_cargo-rudzio"));
        Ok(())
    }
}
