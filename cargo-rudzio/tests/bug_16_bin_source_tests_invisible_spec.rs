//! Behavioural reproducer for Bug #16: `#[rudzio::test]` functions
//! inside `[[bin]]` source files are silently invisible to
//! `cargo rudzio test`.
//!
//! # Symptom
//!
//! When a workspace member declares a `[[bin]]` target whose source
//! tree contains `#[rudzio::test]` functions inside an
//! `#[cfg(any(test, rudzio_test))] mod tests { #[rudzio::suite(...)] ... }`
//! block, `cargo rudzio test` reports a passing run but the bin's
//! tests are never executed and never appear in the `[OK]` output.
//! Exit code is 0; no warning; coverage silently drops.
//!
//! In the downstream report that triggered this spec, 150 of 457
//! tests (~33% of the suite) vanished this way, because the
//! testable surface of the project lived inside `src/bin/...`
//! modules, not inside the library.
//!
//! # Cause sketch (informs the assertion, not the assertion itself)
//!
//! The v2 bridge crate compiles the member's lib source through
//! `<bridge>/src/lib.rs` — the aggregator links against the bridge
//! via `extern crate <bridge>;`, so any `linkme::distributed_slice`
//! statics generated by `#[rudzio::test]` macro expansion inside
//! the bridge's lib compile unit reach the aggregator's
//! `TEST_TOKENS` aggregation. The bridge also declares the member's
//! bins via `[[bin]] path = <member>/src/bin/<name>/main.rs`
//! entries, but bin compile units are NOT linked into the
//! aggregator. Test registrations from inside the bins therefore
//! never reach `TEST_TOKENS`, and the dispatcher has no way to
//! enumerate them: from its view the tests do not exist.
//!
//! # Behavioural assertion
//!
//! Synthetic single-member workspace with one `#[rudzio::test]` in
//! `src/lib.rs` (visible baseline) and one `#[rudzio::test]` in
//! `src/bin/server/ops.rs` (the regression case). Spawn
//! `cargo rudzio test`; assert both test function names appear in
//! the captured stdout and the summary line reports 2 passed.
//! Pre-fix only the lib test runs and the summary says 1 passed.
//!
//! The assertion is **behavioural**: it does not inspect generated
//! source, bridge layout, or codegen artefacts. Any structural fix
//! that makes the bin test run end-to-end satisfies it.
//!
//! # Phase B migration
//!
//! Each `customize_*` helper starts from the suite-provided
//! `ctx.consumer_workspace()` (template = workspace + minimal
//! consumer) and mutates the consumer member to match the
//! fixture's target shape. The template's workspace `Cargo.toml`
//! provides the rudzio path-dep + anyhow workspace deps; per-test
//! `consumer/Cargo.toml` overwrites reference them via
//! `{ workspace = true }`. Bin source files land under
//! `consumer/src/bin/<role>/`.

use std::fs;
use std::io;
use std::path::Path;
use std::process::{Command, Output, Stdio};

use cargo_rudzio_test_helpers::{
    IsolatedCargoSuite, IsolatedCargoTest, RunSummary, assert_exact_test_names, assert_summary,
    combined_output,
};
use rudzio::runtime::tokio::Multithread;

/// Trivial `#[rudzio::test]` block shared by both lib and bin
/// fixtures. The test fn name varies so assertions can grep
/// stdout for which compile unit fired.
fn rudzio_test_block(marker_name: &str) -> String {
    format!(
        "// rudzio_test marker\n\
         #[cfg(any(test, rudzio_test))]\n\
         mod tests {{\n\
         \x20\x20\x20\x20use rudzio::common::context::{{Suite, Test}};\n\
         \x20\x20\x20\x20use rudzio::runtime::tokio::Multithread as TokioMultithread;\n\
         \n\
         \x20\x20\x20\x20#[rudzio::suite([(runtime = TokioMultithread::new, suite = Suite, test = Test)])]\n\
         \x20\x20\x20\x20mod inner {{\n\
         \x20\x20\x20\x20\x20\x20\x20\x20#[rudzio::test]\n\
         \x20\x20\x20\x20\x20\x20\x20\x20fn {marker_name}(_t: &super::Test) -> anyhow::Result<()> {{\n\
         \x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20Ok(())\n\
         \x20\x20\x20\x20\x20\x20\x20\x20}}\n\
         \x20\x20\x20\x20}}\n\
         }}\n",
    )
}

/// Bug #16 Test 1 fixture: lib baseline + bin source test.
///
/// ```text
/// <workspace>/
/// └── consumer/
///     ├── Cargo.toml                   ([lib] + [[bin]] server)
///     └── src/
///         ├── lib.rs                   (1 #[rudzio::test] — lib_baseline_test)
///         └── bin/server/
///             ├── main.rs              (mod ops; trivial fn main)
///             └── ops.rs               (1 #[rudzio::test] — bin_source_test)
/// ```
fn customize_test_1(workspace: &Path) -> io::Result<()> {
    let consumer = workspace.join("consumer");
    let bin_dir = consumer.join("src").join("bin").join("server");
    fs::create_dir_all(&bin_dir)?;

    fs::write(
        consumer.join("Cargo.toml"),
        "[package]\n\
         name = \"consumer\"\n\
         version = \"0.0.0\"\n\
         edition = { workspace = true }\n\
         publish = false\n\
         \n\
         [lib]\n\
         name = \"consumer\"\n\
         path = \"src/lib.rs\"\n\
         \n\
         [[bin]]\n\
         name = \"server\"\n\
         path = \"src/bin/server/main.rs\"\n\
         \n\
         [dev-dependencies]\n\
         rudzio = { workspace = true }\n\
         anyhow = { workspace = true }\n",
    )?;

    fs::write(
        consumer.join("src").join("lib.rs"),
        rudzio_test_block("lib_baseline_test"),
    )?;

    fs::write(
        bin_dir.join("main.rs"),
        "mod ops;\n\
         \n\
         fn main() {\n\
         \x20\x20\x20\x20println!(\"server stub\");\n\
         }\n",
    )?;

    fs::write(bin_dir.join("ops.rs"), rudzio_test_block("bin_source_test"))?;

    Ok(())
}

