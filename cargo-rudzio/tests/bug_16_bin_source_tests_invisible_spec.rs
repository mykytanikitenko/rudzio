/// Phase 0a Test 3 fixture (default-bin shared-mod): src/main.rs +
/// src/lib.rs both declare `mod common;` against the same file.
///
/// ```text
/// <workspace>/
/// └── consumer/
///     ├── Cargo.toml                   ([lib] + [[bin]] consumer-cli)
///     └── src/
///         ├── lib.rs                   (mod common;)
///         ├── main.rs                  (mod common; fn main)
///         └── common.rs                (1 #[rudzio::test] — common_shared_test)
/// ```
fn customize_test_3_default_bin_shared_mod(workspace: &Path) -> io::Result<()> {
    let consumer = workspace.join("consumer");
    let src_dir = consumer.join("src");
    fs::create_dir_all(&src_dir)?;

    fs::write(
        consumer.join("Cargo.toml"),
        "[package]\n\
         name = \"consumer\"\n\
         version = \"0.0.0\"\n\
         edition = { workspace = true }\n\
         publish = false\n\
         \n\
         [lib]\n\
         name = \"consumer\"\n\
         path = \"src/lib.rs\"\n\
         \n\
         [[bin]]\n\
         name = \"consumer-cli\"\n\
         path = \"src/main.rs\"\n\
         \n\
         [dev-dependencies]\n\
         rudzio = { workspace = true }\n\
         anyhow = { workspace = true }\n",
    )?;

    // Lib declares `mod common;`. No direct tests here.
    fs::write(src_dir.join("lib.rs"), "mod common;\n")?;

    // Main also declares `mod common;`. fn main is trivial.
    fs::write(
        src_dir.join("main.rs"),
        "mod common;\n\
         \n\
         fn main() {\n\
         \x20\x20\x20\x20println!(\"consumer-cli stub\");\n\
         }\n",
    )?;

    // common.rs: the shared submodule containing the rudzio test
    // that MUST run exactly once across lib+bin compile.
    fs::write(
        src_dir.join("common.rs"),
        rudzio_test_block("common_shared_test"),
    )?;

    Ok(())
}

