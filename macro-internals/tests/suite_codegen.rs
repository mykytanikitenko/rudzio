//! `expand_suite` codegen reproduction tests, dogfooded on rudzio.

use syn::parse::{Parse, ParseStream};
use syn::token::{Fn, Unsafe};
use syn::{ItemMod, parse_quote};

use proc_macro2::{Delimiter, TokenStream, TokenTree};
use std::mem::take;

use rudzio::common::context::{Suite, Test};
use rudzio::runtime::futures::ThreadPool;
use rudzio_macro_internals::parse::MainArgs;
use rudzio_macro_internals::suite_codegen::expand_suite;

/// The leading attributes + `unsafe fn <ident>` head of a generated
/// run-test helper item. Parses only the head, so the (syn-unparseable)
/// helper body is never touched.
struct FnHead {
    /// The outer attributes (`#[cfg(...)]`, `#[doc(hidden)`) on the helper fn.
    attrs: Vec<syn::Attribute>,
    /// The helper fn's identifier.
    ident: syn::Ident,
}

impl Parse for FnHead {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let attrs = syn::Attribute::parse_outer(input)?;
        let _unsafe: Unsafe = input.parse()?;
        let _fn: Fn = input.parse()?;
        let ident: syn::Ident = input.parse()?;
        // Consume the remainder opaquely: `syn::parse2` requires the whole
        // stream to be consumed, but the helper body is not parseable by `syn`.
        let _rest: TokenStream = input.parse()?;
        Ok(Self { attrs, ident })
    }
}

/// Split a token stream into top-level item streams. An item ends at a
/// depth-0 `;` (struct/static/const/use) or a depth-0 `{ ... }` group
/// (mod/impl/fn/trait/enum body). Paren/bracket groups are atomic in
/// `proc-macro2`, so no explicit delimiter-depth tracking is required.
///
/// Used instead of `syn::File` because the generated owner `run_group` body
/// contains an `if … && let …` let-chain that `syn` 2.0.119 cannot parse; the
/// per-test items themselves (a plain `unsafe fn` and a `static`) parse fine.
fn top_level_items(ts: TokenStream) -> Vec<TokenStream> {
    let mut items = Vec::new();
    let mut current: Vec<TokenTree> = Vec::new();
    for tt in ts {
        let terminates = match &tt {
            TokenTree::Punct(punct) if punct.as_char() == ';' => true,
            TokenTree::Group(group) if group.delimiter() == Delimiter::Brace => true,
            TokenTree::Group(_)
            | TokenTree::Ident(_)
            | TokenTree::Literal(_)
            | TokenTree::Punct(_) => false,
        };
        current.push(tt);
        if terminates {
            items.push(take(&mut current).into_iter().collect());
        }
    }
    if !current.is_empty() {
        items.push(current.into_iter().collect());
    }
    items
}

#[rudzio::suite([
    (runtime = ThreadPool::new, suite = Suite, test = Test),
])]
mod tests {
    use super::{FnHead, ItemMod, MainArgs, Test, expand_suite, parse_quote, top_level_items};

    /// Bug #5: `#[rudzio::suite]` must register tests generated by
    /// `macro_rules!`. Such an invocation reaches the attribute macro as a
    /// `syn::Item::Macro` (pre-expansion), so `expand_suite` cannot see the
    /// test fns it produces. The real contract is that the *expansion* arms
    /// the module so the `#[rudzio::test]` attribute (running post-expansion
    /// on the concrete fn) can register each generated test against this
    /// suite's configs.
    #[rudzio::test]
    fn macro_rules_generated_test_is_registered(_ctx: &Test) -> anyhow::Result<()> {
        let args: MainArgs = parse_quote!([(
            runtime = rudzio::runtime::futures::ThreadPool::new,
            suite = rudzio::common::context::Suite,
            test = rudzio::common::context::Test
        ),]);

        // `make_test!(a);` parses as `syn::Item::Macro` — the exact shape a
        // `macro_rules!` invocation takes in item position. There is no
        // `Item::Fn` in this body, mirroring the pre-expansion AST the
        // `#[rudzio::suite]` attribute actually receives.
        let input_mod: ItemMod = parse_quote! {
            mod tests {
                make_test!(a);
            }
        };

        let expanded = expand_suite(&args, input_mod)?;
        let tokens = expanded.to_string();

        // The hidden forwarding macro (armed inside the module) is present so
        // the `#[rudzio::test]` attribute can route a generated fn into the
        // per-config registration codegen.
        anyhow::ensure!(
            tokens.contains("__rudzio_register_test"),
            "expansion must define the hidden __rudzio_register_test! forwarding macro:\n{tokens}",
        );
        // The forwarding macro delegates to the `__register_test!` proc macro.
        anyhow::ensure!(
            tokens.contains("__register_test"),
            "expansion must forward to ::rudzio::__register_test!:\n{tokens}",
        );
        // The outer module-path const lets inner token statics report the same
        // module path as direct fns.
        anyhow::ensure!(
            tokens.contains("__RUDZIO_SUITE_PATH_TESTS"),
            "expansion must emit the outer module-path const:\n{tokens}",
        );
        Ok(())
    }

    /// Two suites in one file, each holding a `macro_rules!` invocation,
    /// emit their outer-scope type aliases at the same scope. The aliases
    /// must be namespaced per module or rustc rejects the file with E0428.
    #[rudzio::test]
    fn two_macro_suites_emit_distinct_outer_aliases(_ctx: &Test) -> anyhow::Result<()> {
        let args: MainArgs = parse_quote!([(
            runtime = rudzio::runtime::futures::ThreadPool::new,
            suite = rudzio::common::context::Suite,
            test = rudzio::common::context::Test
        ),]);
        let first: ItemMod = parse_quote! { mod first { make_test!(a); } };
        let second: ItemMod = parse_quote! { mod second { make_test!(a); } };

        let first_tokens = expand_suite(&args, first)?.to_string();
        let second_tokens = expand_suite(&args, second)?.to_string();

        anyhow::ensure!(
            first_tokens.contains("__RudzioRuntimeFirst0"),
            "first suite alias must carry its module name:\n{first_tokens}",
        );
        anyhow::ensure!(
            second_tokens.contains("__RudzioRuntimeSecond0"),
            "second suite alias must carry its module name:\n{second_tokens}",
        );
        anyhow::ensure!(
            !first_tokens.contains("__RudzioRuntimeSecond0")
                && !second_tokens.contains("__RudzioRuntimeFirst0"),
            "aliases must not leak across suites",
        );
        Ok(())
    }

    /// A direct `#[rudzio::test]` fn carrying `#[cfg(feature =
    /// "never-enabled")]` must have that `#[cfg]` re-emitted on BOTH the
    /// generated `__rudzio_run_test_*` helper fn and the `__RUDZIO_TOKEN_*`
    /// static, so cfg-stripping removes them together with the fn (E0425).
    /// Inspected from the parsed `syn::File`, not by string containment.
    #[rudzio::test]
    fn direct_cfg_gated_test_propagates_cfg_to_registration_items(
        _ctx: &Test,
    ) -> anyhow::Result<()> {
        let args: MainArgs = parse_quote!([(
            runtime = rudzio::runtime::futures::ThreadPool::new,
            suite = rudzio::common::context::Suite,
            test = rudzio::common::context::Test
        ),]);
        let input_mod: ItemMod = parse_quote! {
            mod tests {
                use super::Test;

                #[cfg(feature = "never-enabled")]
                #[rudzio::test]
                async fn gated(_ctx: &Test) -> anyhow::Result<()> { Ok(()) }
            }
        };

        let expanded = expand_suite(&args, input_mod)?;

        let has_cfg =
            |attrs: &[syn::Attribute]| attrs.iter().any(|attr| attr.path().is_ident("cfg"));

        let mut helper_cfg = None;
        let mut token_cfg = None;
        for item_ts in top_level_items(expanded) {
            if let Ok(head) = syn::parse2::<FnHead>(item_ts.clone())
                && head.ident == "__rudzio_run_test_tests_gated_0"
            {
                helper_cfg = Some(has_cfg(&head.attrs));
            }
            if let Ok(syn::Item::Static(statik)) = syn::parse2::<syn::Item>(item_ts)
                && statik.ident == "__RUDZIO_TOKEN_TESTS_GATED_0"
            {
                token_cfg = Some(has_cfg(&statik.attrs));
            }
        }

        anyhow::ensure!(
            helper_cfg == Some(true),
            "generated run_test helper fn must carry the test fn's #[cfg] (got {helper_cfg:?})",
        );
        anyhow::ensure!(
            token_cfg == Some(true),
            "generated token static must carry the test fn's #[cfg] (got {token_cfg:?})",
        );
        Ok(())
    }

    /// A raw-identifier test name (`fn r#type`) must not panic the generated
    /// hidden idents. `format_ident!` over `r#type` would emit `R#TYPE`
    /// (an invalid fragment); the codegen strips the `r#` prefix so the token
    /// static and run-test helper names are well-formed.
    #[rudzio::test]
    fn raw_ident_test_name_is_sanitized(_ctx: &Test) -> anyhow::Result<()> {
        let args: MainArgs = parse_quote!([(
            runtime = rudzio::runtime::futures::ThreadPool::new,
            suite = rudzio::common::context::Suite,
            test = rudzio::common::context::Test
        ),]);
        let input_mod: ItemMod = parse_quote! {
            mod tests {
                use super::Test;

                #[rudzio::test]
                async fn r#type(_ctx: &Test) -> anyhow::Result<()> { Ok(()) }
            }
        };

        let expanded = expand_suite(&args, input_mod)?;
        let tokens = expanded.to_string();

        anyhow::ensure!(
            !tokens.contains("R#TYPE"),
            "raw-ident `r#` fragment must not leak into generated idents:\n{tokens}",
        );
        anyhow::ensure!(
            tokens.contains("__RUDZIO_TOKEN_TESTS_TYPE_0"),
            "expected sanitized token-static name, got:\n{tokens}",
        );
        anyhow::ensure!(
            tokens.contains("__rudzio_run_test_tests_type_0"),
            "expected sanitized run-test-helper name, got:\n{tokens}",
        );
        Ok(())
    }
}
